//! Generates [`TransitionType`] and [`EffectConfig`] from `director-core::api_catalog`
//! so schema enums cannot drift from the canonical catalog.

use director_core::api_catalog::{EFFECT_CATALOG, TRANSITION_CATALOG};
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let generated = out_dir.join("generated_schema_enums.rs");
    fs::write(&generated, generate()).expect("write generated schema enums");
    println!("cargo:rerun-if-changed=../director-core/src/api_catalog.rs");
}

fn generate() -> String {
    let mut out = String::new();
    out.push_str("// @generated by build.rs — do not edit.\n");
    out.push_str("use director_core::animation::EasingType;\n");
    out.push_str("use director_core::types::Color;\n");
    out.push_str("use schemars::JsonSchema;\n");
    out.push_str("use serde::{Deserialize, Serialize};\n\n");

    out.push_str(&generate_transition_type());
    out.push_str(&generate_transition_config());
    out.push_str(&generate_effect_config());

    out
}

fn generate_transition_type() -> String {
    let mut s = String::from(
        "/// Visual transition type between scenes (generated from [`director_core::api_catalog`]).\n",
    );
    s.push_str("#[derive(Serialize, Deserialize, Debug, Clone, Default, JsonSchema)]\n");
    s.push_str("#[serde(tag = \"type\", rename_all = \"snake_case\")]\n");
    s.push_str("pub enum TransitionType {\n");

    for entry in TRANSITION_CATALOG {
        let variant = snake_to_pascal(entry.name);
        if entry.name == "fade" {
            s.push_str("    #[default]\n");
        }
        if entry.params.is_empty() {
            s.push_str(&format!("    {variant},\n"));
        } else {
            s.push_str(&format!("    {variant} {{\n"));
            for (param, ty) in entry.params {
                match *ty {
                    "f32" => {
                        if let Some(default_fn) = transition_f32_default(entry.name, param) {
                            s.push_str(&format!(
                                "        #[serde(default = \"{default_fn}\")]\n"
                            ));
                        } else {
                            s.push_str("        #[serde(default)]\n");
                        }
                        s.push_str(&format!("        {param}: f32,\n"));
                    }
                    other => panic!(
                        "unsupported transition param type {other} on {}.{param}",
                        entry.name
                    ),
                }
            }
            s.push_str("    },\n");
        }
    }
    s.push_str("}\n\n");
    s.push_str(&generate_transition_default_fns());
    s
}

fn generate_transition_config() -> String {
    r#"/// Configuration for a scene-to-scene transition.
#[derive(Serialize, Deserialize, Debug, Clone, JsonSchema)]
pub struct TransitionConfig {
    /// Duration in seconds
    pub duration: f64,
    /// Easing function (default: Linear)
    #[serde(default = "default_easing")]
    pub easing: EasingType,
    #[serde(flatten)]
    pub kind: TransitionType,
}

fn default_easing() -> EasingType {
    EasingType::Linear
}

"#
    .to_string()
}

fn generate_transition_default_fns() -> String {
    r#"fn default_wave_amplitude() -> f32 {
    0.1
}
fn default_wave_frequency() -> f32 {
    5.0
}
fn default_glitch_intensity() -> f32 {
    0.5
}
fn default_iris_end_radius() -> f32 {
    500.0
}
fn default_spiral_rotations() -> f32 {
    2.0
}

"#
    .to_string()
}

fn transition_f32_default(transition: &str, param: &str) -> Option<&'static str> {
    match (transition, param) {
        ("wave", "amplitude") => Some("default_wave_amplitude"),
        ("wave", "frequency") => Some("default_wave_frequency"),
        ("glitch", "intensity") => Some("default_glitch_intensity"),
        ("iris", "end_radius") => Some("default_iris_end_radius"),
        ("spiral", "rotations") => Some("default_spiral_rotations"),
        _ => None,
    }
}

fn generate_effect_config() -> String {
    let mut s = String::from(
        "/// Configuration for visual effects applied to nodes (generated from [`director_core::api_catalog`]).\n",
    );
    s.push_str("#[derive(Serialize, Deserialize, Debug, Clone, JsonSchema)]\n");
    s.push_str("#[serde(tag = \"effect\", rename_all = \"snake_case\")]\n");
    s.push_str("pub enum EffectConfig {\n");

    for entry in EFFECT_CATALOG {
        let variant = snake_to_pascal(entry.schema_tag);
        if entry.params.is_empty() {
            s.push_str(&format!("    /// {desc}\n", desc = entry.description));
            s.push_str(&format!("    {variant},\n"));
        } else {
            s.push_str(&format!("    /// {desc}\n", desc = entry.description));
            s.push_str(&format!("    {variant} {{\n"));
            for (param, ty) in entry.params {
                match *ty {
                    "f32" => {
                        if let Some(default_fn) = effect_f32_default(entry.schema_tag, param) {
                            s.push_str(&format!(
                                "        #[serde(default = \"{default_fn}\")]\n"
                            ));
                        } else {
                            s.push_str("        #[serde(default)]\n");
                        }
                        s.push_str(&format!("        {param}: f32,\n"));
                    }
                    "u32" => {
                        if let Some(default_fn) = effect_u32_default(entry.schema_tag, param) {
                            s.push_str(&format!(
                                "        #[serde(default = \"{default_fn}\")]\n"
                            ));
                        } else {
                            s.push_str("        #[serde(default)]\n");
                        }
                        s.push_str(&format!("        {param}: u32,\n"));
                    }
                    "Color" => {
                        s.push_str("        #[serde(default)]\n");
                        s.push_str(&format!("        {param}: Option<Color>,\n"));
                    }
                    "String" => {
                        s.push_str(&format!("        {param}: String,\n"));
                    }
                    "[f32; 20]" => {
                        s.push_str(&format!("        {param}: Vec<f32>,\n"));
                    }
                    "Map" => {
                        s.push_str("        #[serde(default)]\n");
                        s.push_str(&format!(
                            "        {param}: std::collections::HashMap<String, f32>,\n"
                        ));
                    }
                    other => {
                        panic!(
                            "unsupported effect param type {other} on {}.{param}",
                            entry.schema_tag
                        )
                    }
                }
            }
            s.push_str("    },\n");
        }
    }
    s.push_str("}\n\n");
    s.push_str(&generate_effect_default_fns());
    s
}

fn generate_effect_default_fns() -> String {
    r#"fn default_blur() -> f32 {
    10.0
}
fn default_samples() -> u32 {
    16
}
fn default_grain_intensity() -> f32 {
    0.1
}
fn default_grain_size() -> f32 {
    1.0
}
fn default_contrast() -> f32 {
    1.0
}
fn default_brightness() -> f32 {
    0.0
}

"#
    .to_string()
}

fn effect_f32_default(effect: &str, param: &str) -> Option<&'static str> {
    match (effect, param) {
        ("blur", "sigma") | ("drop_shadow", "blur") | ("directional_blur", "strength") => {
            Some("default_blur")
        }
        ("grain", "intensity") => Some("default_grain_intensity"),
        ("grain", "size") => Some("default_grain_size"),
        ("contrast", "value") => Some("default_contrast"),
        ("brightness", "value") => Some("default_brightness"),
        _ => None,
    }
}

fn effect_u32_default(effect: &str, param: &str) -> Option<&'static str> {
    match (effect, param) {
        ("directional_blur", "samples") => Some("default_samples"),
        _ => None,
    }
}

fn snake_to_pascal(s: &str) -> String {
    s.split('_')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
            }
        })
        .collect()
}