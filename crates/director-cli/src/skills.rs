//! `skills`: agent skills generated from the MCP tool schemas, so the skill
//! text follows the tools it documents.

use crate::mcp;
use clap::Parser;
use director_host::ErrorCode;
use serde_json::{json, Value};
use std::fmt::Write;
use std::path::{Path, PathBuf};

pub const SKILL: &str = "director-mcp";

#[derive(Parser, Debug)]
pub struct SkillsArgs {
    /// Skills directory; each skill lands in `<DIR>/<name>/`
    dir: PathBuf,
}

pub fn run(args: SkillsArgs) -> i32 {
    match write(&args.dir) {
        Ok(files) => {
            println!("{}", json!({ "skill": SKILL, "files": files }));
            0
        }
        Err(error) => {
            eprintln!("{error}");
            1
        }
    }
}

/// Write every generated file under `dir/director-mcp/`.
fn write(dir: &Path) -> std::io::Result<Vec<PathBuf>> {
    let dir = dir.join(SKILL);
    std::fs::create_dir_all(&dir)?;
    files()
        .into_iter()
        .map(|(name, text)| {
            let path = dir.join(name);
            std::fs::write(&path, text)?;
            Ok(path)
        })
        .collect()
}

/// The generated skill files by name.
pub fn files() -> [(&'static str, String); 2] {
    let tools = mcp::tools();
    let listing = serde_json::to_string_pretty(&json!({ "tools": tools })).expect("tool JSON") + "\n";
    [("SKILL.md", skill(&tools)), ("tools.json", listing)]
}

fn skill(tools: &[Value]) -> String {
    let mut out = String::new();
    out.push_str(concat!(
        "---\n",
        "name: director-mcp\n",
        "description: Open, outline, read nodes, diff, patch, inspect, score, paint and export Director video projects through the director-engine MCP server. Use when an agent edits or renders HTML, Rhai or .dirproj video through MCP tools.\n",
        "---\n\n",
        "<!-- Generated by `director-engine skills` from the MCP tool schemas. Regenerate it instead of editing it. -->\n\n",
        "# Director MCP\n\n",
    ));
    out.push_str(mcp::INSTRUCTIONS);
    out.push_str(concat!(
        "\n\n## Setup\n\n",
        "Register the server in the MCP client configuration:\n\n",
        "```json\n",
        "{\"mcpServers\":{\"director\":{\"command\":\"director-engine\",\"args\":[\"mcp\"]}}}\n",
        "```\n\n",
        "Add `\"--gpu\"` to `args` on a Vulkan build. Paths resolve against the server's working directory. `render_frame` and `export` outputs must land inside that directory or the session's input directory; add `\"--allow-dir\", \"<DIR>\"` to `args` for another root. Other paths fail with `output_outside_root`. Send `_meta.progressToken` with `qa` or `export` to get `notifications/progress`.\n\n",
        "## Loop\n\n",
        "1. `open` the input. Keep `session`, and read authored node names in `outline.roots`.\n",
        "2. `render_frame` at a few times and look at the frames.\n",
        "3. `node` with `leaves: true` lists a node's settable JSON pointers and values. Pick a `path` there.\n",
        "4. `patch` with `base_revision` set to the last revision. On `conflict`, read `outline` and write the ops again.\n",
        "5. `inspect` at a time for layout bounds, timeline and audio.\n",
        "6. `qa` and patch until `pass` holds, following each issue's `fix`; aim for a score of 100.\n",
        "7. `diff` two sessions for the ops that turn one input into the other.\n",
        "8. `export` with `draft: true`, check it, then export without `draft`.\n",
        "9. `close` sessions when done.\n\n",
        "## Tools\n",
    ));
    for tool in tools {
        let _ = write!(out, "\n### `{}`\n\n{}\n", tool["name"].as_str().unwrap_or_default(), text(&tool["description"]));
        if tool["annotations"]["readOnlyHint"] == true {
            out.push_str("\nRead only.\n");
        }
        out.push('\n');
        arguments(&tool["inputSchema"], &mut out);
    }
    out.push_str("\n## Errors\n\nA failed tool returns `isError: true` with `{\"error\":{\"code\",\"message\"}}` as text and structured content. Codes:\n\n");
    for variant in mcp::schema::<ErrorCode>()["oneOf"].as_array().into_iter().flatten() {
        let _ = writeln!(out, "- `{}`: {}", text(&variant["enum"][0]), text(&variant["description"]));
    }
    out
}

/// One bullet per property, required ones first, with nested bullets for
/// tagged variants such as patch ops.
fn arguments(schema: &Value, out: &mut String) {
    let required: Vec<&str> = schema["required"].as_array().into_iter().flatten().filter_map(Value::as_str).collect();
    let Some(properties) = schema["properties"].as_object() else {
        return;
    };
    let mut names: Vec<&String> = properties.keys().collect();
    names.sort_by_key(|name| !required.contains(&name.as_str()));
    for name in names {
        let property = &properties[name];
        let need = match property.get("default") {
            _ if required.contains(&name.as_str()) => "required".to_string(),
            Some(default) => format!("optional, default `{default}`"),
            None => "optional".to_string(),
        };
        let _ = writeln!(out, "- `{name}` ({}, {need}): {}", type_of(property), text(&property["description"]));
        let items = if property["items"].is_object() { &property["items"] } else { property };
        for variant in items["oneOf"].as_array().into_iter().flatten() {
            variant_line(variant, out);
        }
    }
}

/// `  - `{"op":"set", node, path, value}`: description` for a tagged object variant.
fn variant_line(variant: &Value, out: &mut String) {
    let Some(properties) = variant["properties"].as_object() else {
        return;
    };
    let tag = properties.iter().find_map(|(field, schema)| match schema["enum"].as_array() {
        Some(values) if values.len() == 1 => Some((field.as_str(), values[0].to_string())),
        _ => None,
    });
    let mut fields: Vec<String> = tag.iter().map(|(field, value)| format!("\"{field}\":{value}")).collect();
    fields.extend(properties.iter().filter(|(field, _)| tag.as_ref().is_none_or(|(tag, _)| *tag != field.as_str())).map(|(field, schema)| format!("{field}: {}", type_of(schema))));
    let _ = writeln!(out, "  - `{{{}}}`: {}", fields.join(", "), text(&variant["description"]));
}

/// A short type for a schema: `string`, `integer`, `"a" | "b"`, `array of …`.
fn type_of(schema: &Value) -> String {
    if let Some(values) = schema["enum"].as_array() {
        return values.iter().map(Value::to_string).collect::<Vec<_>>().join(" | ");
    }
    if let Some(variants) = schema["anyOf"].as_array().or(schema["oneOf"].as_array()) {
        let mut types: Vec<String> = Vec::new();
        for variant in variants {
            let kind = type_of(variant);
            if !types.contains(&kind) {
                types.push(kind);
            }
        }
        return types.join(" | ");
    }
    let kinds: Vec<&str> = match &schema["type"] {
        Value::String(kind) => vec![kind.as_str()],
        Value::Array(kinds) => kinds.iter().filter_map(Value::as_str).filter(|kind| *kind != "null").collect(),
        _ => return "any".into(),
    };
    kinds
        .iter()
        .map(|kind| match *kind {
            "array" => format!("array of {}", type_of(&schema["items"])),
            "object" => match schema["properties"].as_object() {
                // Tagged variants list under their property.
                Some(properties) if properties.values().any(|field| field["enum"].as_array().is_some_and(|values| values.len() == 1)) => "object".into(),
                Some(properties) => format!("{{{}}}", properties.keys().cloned().collect::<Vec<_>>().join(", ")),
                None => "object".into(),
            },
            kind => kind.into(),
        })
        .collect::<Vec<_>>()
        .join(" | ")
}

/// A description on one line.
fn text(value: &Value) -> String {
    value.as_str().unwrap_or_default().split_whitespace().collect::<Vec<_>>().join(" ")
}

#[cfg(test)]
mod tests {
    use super::{files, SKILL};
    use std::path::PathBuf;

    #[test]
    fn checked_in_skill_matches_the_tool_schemas() {
        let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../.agent/skills").join(SKILL);
        for (name, generated) in files() {
            let checked_in = std::fs::read_to_string(dir.join(name)).unwrap_or_default().replace("\r\n", "\n");
            assert!(
                checked_in == generated,
                "{SKILL}/{name} is stale; run `director-engine skills .agent/skills`"
            );
        }
    }

    #[test]
    fn skill_documents_every_tool_argument_and_error_code() {
        let [(_, skill), (_, listing)] = files();
        let listing: serde_json::Value = serde_json::from_str(&listing).unwrap();
        for tool in listing["tools"].as_array().unwrap() {
            assert!(skill.contains(&format!("### `{}`", tool["name"].as_str().unwrap())));
            for argument in tool["inputSchema"]["properties"].as_object().unwrap().keys() {
                assert!(skill.contains(&format!("- `{argument}` (")), "{argument}");
            }
        }
        assert!(skill.contains(r#"- `ops` (array of object, required)"#), "{skill}");
        assert!(skill.contains(r#"`{"op":"set_document", path: string, value: any}`"#), "{skill}");
        assert!(skill.contains(r#"- `encoder` ("software" | "nvenc", optional, default `"software"`): Video encoder"#), "{skill}");
        assert!(skill.contains("- `missing_font`: "), "{skill}");
    }
}
